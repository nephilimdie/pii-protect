"""Genre templates for the Italian PII benchmark (legal, HR, tax, real estate/insurance,
e-mail/tickets, AI chat prompts, logs/JSON, negative-only documents).

Why: each genre has its own layout and look-alikes (law citations, invoice numbers, F24 codes).
What: one function per sub-genre writes into a gold.Doc; GENRES lists counts per sub-genre.
Test: generate.generate() builds every template; tests check span integrity and counts.
"""
from __future__ import annotations

import itdata as D
from gold import (Doc, P, address, body, born, cf, company, digits, dob, docdate, email, iban, law,
                  money, name, phone, rg)

# ---------------------------------------------------------------- legal
def t_citazione(d: Doc) -> None:
    a, b, lawyer = P(d), P(d), P(d)
    d.t("ATTO DI CITAZIONE\n")
    d.t("Il/La ")
    name(d, a)
    d.t(" (C.F. ")
    cf(d, a)
    d.t("), ")
    born(d, a)
    d.t(", residente in ")
    address(d, a)
    d.t(", rappresentato e difeso dall'Avv. ")
    name(d, lawyer)
    d.t(" (PEC: ")
    email(d, lawyer, pec=True)
    d.t("), con studio in ")
    address(d, lawyer)
    d.t(",\nCITA\n")
    name(d, b)
    d.t(", residente in ")
    address(d, b)
    d.t(", a comparire innanzi al ")
    body(d)
    d.t(" all'udienza del ")
    docdate(d)
    d.t(", per ivi sentir accertare la responsabilità ex ")
    law(d)
    d.t(" e condannare al pagamento di ")
    money(d)
    d.t(", oltre interessi.\n")


